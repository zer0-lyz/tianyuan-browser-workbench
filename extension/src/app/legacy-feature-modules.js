function legacyFeature(manifest) {
  return {
    manifest: {
      type: "feature",
      stage: "stable",
      storageVersion: 1,
      usesLegacyScope: false,
      ...manifest,
      messageNamespace: manifest.messageNamespace || manifest.id,
    },
    create() {
      return {
        initialize() {},
        activate() {},
        deactivate() {},
        dispose() {},
      };
    },
  };
}

